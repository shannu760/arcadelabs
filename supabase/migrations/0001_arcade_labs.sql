-- ARCADE LABS — schema, row level security and reward engine
--
-- Apply with:  Supabase dashboard → SQL Editor → paste → Run
-- or:          supabase db push   (if you use the CLI)
--
-- Design notes
--   * The browser never writes scores. Every session goes through
--     arcade_complete_session(), which recalculates the score, XP and
--     K-Points from raw session facts, applies the daily cap and writes
--     an append-only ledger row keyed by an idempotency key.
--   * Direct insert/update on reward tables is denied by RLS; only the
--     SECURITY DEFINER functions can write.
--   * Daily buckets use Asia/Kolkata.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- tables

create table if not exists public.arcade_games (
  id          bigint generated by default as identity primary key,
  game_slug   text not null unique,
  title       text not null,
  category    text not null,
  difficulty  text not null default 'mixed',
  is_active   boolean not null default true
);

create table if not exists public.arcade_profiles (
  id                uuid primary key references auth.users (id) on delete cascade,
  username          text not null default 'PLAYER',
  avatar            text not null default 'default',
  level             integer not null default 1 check (level >= 1),
  total_xp          bigint not null default 0 check (total_xp >= 0),
  k_points          integer not null default 0 check (k_points >= 0),
  idea_points       integer not null default 0 check (idea_points >= 0),
  current_streak    integer not null default 0 check (current_streak >= 0),
  longest_streak    integer not null default 0 check (longest_streak >= 0),
  last_streak_date  date,
  created_at        timestamptz not null default now()
);

create table if not exists public.arcade_sessions (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references auth.users (id) on delete cascade,
  game_slug    text not null references public.arcade_games (game_slug),
  score        integer not null check (score >= 0),
  xp_earned    integer not null default 0 check (xp_earned >= 0),
  kp_earned    integer not null default 0 check (kp_earned >= 0),
  accuracy     numeric(5, 4) check (accuracy is null or (accuracy >= 0 and accuracy <= 1)),
  duration     integer not null default 0 check (duration >= 0),
  payload      jsonb not null default '{}'::jsonb,
  client_id    text not null,
  verified     boolean not null default true,
  created_at   timestamptz not null default now(),
  unique (user_id, client_id)
);

create index if not exists arcade_sessions_user_idx on public.arcade_sessions (user_id, created_at desc);
create index if not exists arcade_sessions_game_idx on public.arcade_sessions (game_slug, score desc);
create index if not exists arcade_sessions_created_idx on public.arcade_sessions (created_at desc);

create table if not exists public.arcade_reward_transactions (
  id                  uuid primary key default gen_random_uuid(),
  user_id             uuid not null references auth.users (id) on delete cascade,
  source_type         text not null,
  source_id           text not null,
  reward_type         text not null,
  amount              integer not null,
  reason              text not null default '',
  verification_status text not null default 'verified',
  idempotency_key     text not null,
  created_at          timestamptz not null default now(),
  unique (user_id, idempotency_key)
);

create index if not exists arcade_ledger_user_idx on public.arcade_reward_transactions (user_id, created_at desc);

create table if not exists public.arcade_achievements (
