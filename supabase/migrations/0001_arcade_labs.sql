-- ---------------------------------------------------------------- helpers

create or replace function public.arcade_today()
returns date
language sql
stable
as $$
  select (now() at time zone 'Asia/Kolkata')::date;
$$;

create or replace function public.arcade_level_from_xp(p_xp bigint)
returns integer
language plpgsql
immutable
as $$
declare
  lvl integer := 1;
  rest bigint := greatest(coalesce(p_xp, 0), 0);
begin
  while rest >= 100 * lvl loop
    rest := rest - 100 * lvl;
    lvl := lvl + 1;
  end loop;
  return lvl;
end;
$$;

create or replace function public.arcade_kp_used_today(p_user uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(amount), 0)::integer
  from public.arcade_reward_transactions
  where user_id = p_user
    and reward_type = 'kp'
    and amount > 0
    and (created_at at time zone 'Asia/Kolkata')::date = public.arcade_today();
$$;

-- Internal: append a ledger row, enforcing the global 100 KP daily cap and
-- the 20 KP daily-challenge ceiling. Returns the amount actually granted.
create or replace function public.arcade_grant(
  p_user uuid,
  p_source_type text,
  p_source_id text,
  p_reward_type text,
  p_amount integer,
  p_key text,
  p_reason text default ''
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  granted integer := p_amount;
  used_today integer;
  used_category integer;
  ceiling integer;
begin
  if p_amount is null or p_amount = 0 then
    return 0;
  end if;

  if exists (
    select 1 from public.arcade_reward_transactions
    where user_id = p_user and idempotency_key = p_key
  ) then
    return 0;
  end if;

  if p_reward_type = 'kp' then
    used_today := public.arcade_kp_used_today(p_user);
    ceiling := case when p_source_type = 'daily-challenge' then 20 else 100 end;
    used_category := coalesce((
      select sum(amount) from public.arcade_reward_transactions
      where user_id = p_user
        and reward_type = 'kp'
        and amount > 0
        and source_type = p_source_type
        and (created_at at time zone 'Asia/Kolkata')::date = public.arcade_today()
    ), 0)::integer;

    granted := least(p_amount, 100 - used_today, ceiling - used_category);
    if granted is null or granted < 0 then
      granted := 0;
    end if;

    if granted = 0 then
      return 0;
    end if;

    update public.arcade_profiles
      set k_points = k_points + granted
      where id = p_user;
  elsif p_reward_type = 'kp-spend' then
    -- spending is negative and bypasses the earning cap
    granted := -abs(p_amount);
    update public.arcade_profiles
      set k_points = greatest(0, k_points - abs(p_amount))
      where id = p_user;
  elsif p_reward_type = 'xp' then
    granted := greatest(0, p_amount);
    update public.arcade_profiles
      set total_xp = total_xp + granted,
          level = public.arcade_level_from_xp(total_xp + granted)
      where id = p_user;
  end if;

  insert into public.arcade_reward_transactions
    (user_id, source_type, source_id, reward_type, amount, reason, idempotency_key)
  values
    (p_user, p_source_type, p_source_id, p_reward_type, granted, coalesce(p_reason, ''), p_key);

  return granted;
end;
$$;

