create or replace function public.arcade_complete_session(
  p_game_slug text,
  p_payload jsonb,
  p_client_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  calc jsonb;
  prof public.arcade_profiles;
  session_uuid uuid;
  v_score integer;
  v_xp integer;
  v_kp integer;
  v_accuracy numeric;
  granted integer := 0;
  kp_total integer := 0;
  xp_total integer := 0;
  today date := public.arcade_today();
  lvl integer;
  new_level integer;
  level_kp integer;
  distinct_games integer;
  quiz_count integer;
  memory_count integer;
  coding_count integer;
  puzzle_count integer;
  perfect_quizzes integer;
  perfect_games integer;
  total_sessions integer;
  ach record;
  ctx_ok boolean;
  unlocked jsonb := '[]'::jsonb;
  challenges jsonb := '[]'::jsonb;
  streak_kp integer := 0;
  gap integer;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if p_client_id is null or length(p_client_id) < 8 then
    raise exception 'client id required' using errcode = '22023';
  end if;

  -- idempotency: returning the stored result prevents double payouts
  if exists (select 1 from public.arcade_sessions where user_id = uid and client_id = p_client_id) then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;

  insert into public.arcade_profiles (id, username)
  values (uid, coalesce((auth.jwt() -> 'user_metadata' ->> 'nickname'), 'PLAYER'))
  on conflict (id) do nothing;

  select * into prof from public.arcade_profiles where id = uid;
  calc := public.arcade_calc(p_game_slug, p_payload);

  v_score := coalesce((calc->>'score')::integer, 0);
  v_xp := coalesce((calc->>'xp')::integer, 0);
  v_kp := coalesce((calc->>'kp')::integer, 0);
  v_accuracy := nullif(calc->>'accuracy', '')::numeric;

  if v_score = 0 and v_xp = 0 then
    return jsonb_build_object('ok', false, 'reason', 'session did not meet the minimum completion bar');
  end if;

  insert into public.arcade_sessions
    (user_id, game_slug, score, xp_earned, kp_earned, accuracy, duration, payload, client_id)
  values
    (uid, p_game_slug, v_score, v_xp, v_kp, v_accuracy,
     coalesce((p_payload->>'durationSec')::integer, 0), p_payload, p_client_id)
  returning id into session_uuid;

  -- 3. XP
  xp_total := public.arcade_grant(uid, 'game', p_game_slug, 'xp', v_xp,
                                  'session:' || p_client_id || ':xp', p_game_slug);
  -- 4/5. K-Points with the daily cap inside arcade_grant
  kp_total := public.arcade_grant(uid, p_game_slug, p_game_slug, 'kp', v_kp,
                                  'session:' || p_client_id || ':kp', p_game_slug);

  -- 6/7. level progression, 10 KP per level (+25 every fifth)
  select level into lvl from public.arcade_profiles where id = uid;
  new_level := public.arcade_level_from_xp((select total_xp from public.arcade_profiles where id = uid));
  while lvl < new_level loop
    lvl := lvl + 1;
    level_kp := 10 + case when lvl % 5 = 0 then 25 else 0 end;
    perform public.arcade_grant(uid, 'level-up', lvl::text, 'kp', level_kp,
                                'level:' || lvl, 'Reached level ' || lvl);
  end loop;
  update public.arcade_profiles set level = new_level where id = uid;

  -- 8. achievements
  select count(*) into total_sessions from public.arcade_sessions where user_id = uid;
  select count(*) into quiz_count from public.arcade_sessions where user_id = uid and game_slug = 'brain-battle';
  select count(*) into memory_count from public.arcade_sessions where user_id = uid and game_slug = 'memory-champion';
  select coalesce(sum((payload->>'correctCount')::integer), 0) into coding_count
    from public.arcade_sessions where user_id = uid and game_slug = 'code-escape';
  select count(*) into puzzle_count from public.arcade_sessions
    where user_id = uid and game_slug in ('sudoku-master', '2048-challenge');
  select count(*) into perfect_quizzes from public.arcade_sessions
    where user_id = uid and game_slug = 'brain-battle' and accuracy = 1;
  select count(*) into perfect_games from public.arcade_sessions
    where user_id = uid and accuracy = 1;
  select current_streak into gap from public.arcade_profiles where id = uid;

  for ach in
    select * from (values
      ('first-victory', total_sessions >= 1, 10, 2),
      ('brain-master', quiz_count >= 10, 25, 5),
      ('memory-expert', memory_count >= 10, 25, 5),
      ('coding-beginner', coding_count >= 5, 20, 5),
      ('coding-expert', coding_count >= 50, 100, 15),
      ('puzzle-solver', puzzle_count >= 20, 40, 8),
      ('seven-day-streak', gap >= 7, 50, 15),
      ('quiz-champion', perfect_quizzes >= 10, 50, 10),
      ('perfect-score', perfect_games >= 1, 25, 5)
    ) as t(slug, ok, xp, kp)
  loop
    if not ach.ok then continue; end if;
    if exists (select 1 from public.arcade_achievements where user_id = uid and achievement_slug = ach.slug) then
      continue;
    end if;
    insert into public.arcade_achievements (user_id, achievement_slug) values (uid, ach.slug);
    perform public.arcade_grant(uid, 'achievement', ach.slug, 'xp', ach.xp,
                                'achievement:' || ach.slug || ':xp', ach.slug);
    perform public.arcade_grant(uid, 'achievement', ach.slug, 'kp', ach.kp,
                                'achievement:' || ach.slug || ':kp', ach.slug);
    unlocked := unlocked || jsonb_build_array(ach.slug);
  end loop;

  -- 9. daily challenges
  select count(distinct game_slug) into distinct_games
    from public.arcade_sessions
    where user_id = uid and (created_at at time zone 'Asia/Kolkata')::date = today;

  if distinct_games >= 1 and not exists (
    select 1 from public.arcade_reward_transactions
    where user_id = uid and idempotency_key = 'daily:daily-any:' || today
  ) then
    perform public.arcade_grant(uid, 'daily-challenge', 'daily-any', 'xp', 10, 'daily:daily-any:' || today || ':xp', 'Open the arcade');
    perform public.arcade_grant(uid, 'daily-challenge', 'daily-any', 'kp', 2, 'daily:daily-any:' || today, 'Open the arcade');
    challenges := challenges || jsonb_build_array('daily-any');
  end if;

  if v_accuracy is not null and v_accuracy >= 0.8 and p_game_slug in ('brain-battle', 'geo-genius') and not exists (
    select 1 from public.arcade_reward_transactions
    where user_id = uid and idempotency_key = 'daily:daily-accuracy:' || today
  ) then
    perform public.arcade_grant(uid, 'daily-challenge', 'daily-accuracy', 'xp', 15, 'daily:daily-accuracy:' || today || ':xp', 'Sharp shooter');
    perform public.arcade_grant(uid, 'daily-challenge', 'daily-accuracy', 'kp', 3, 'daily:daily-accuracy:' || today, 'Sharp shooter');
    challenges := challenges || jsonb_build_array('daily-accuracy');
  end if;

  if distinct_games >= 3 and not exists (
    select 1 from public.arcade_reward_transactions
    where user_id = uid and idempotency_key = 'daily:daily-three:' || today
  ) then
    perform public.arcade_grant(uid, 'daily-challenge', 'daily-three', 'xp', 20, 'daily:daily-three:' || today || ':xp', 'Triple threat');
    perform public.arcade_grant(uid, 'daily-challenge', 'daily-three', 'kp', 5, 'daily:daily-three:' || today, 'Triple threat');
    challenges := challenges || jsonb_build_array('daily-three');
  end if;

  -- 10. streak: one reward per Kolkata calendar day
  select * into prof from public.arcade_profiles where id = uid;

  if prof.last_streak_date is null or prof.last_streak_date < today then
    gap := case
      when prof.last_streak_date = today - 1 then prof.current_streak + 1
      else 1
    end;
    update public.arcade_profiles
      set current_streak = gap,
          longest_streak = greatest(longest_streak, gap),
          last_streak_date = today
      where id = uid;
    if gap > 1 then
      streak_kp := public.arcade_grant(
        uid, 'streak', today::text, 'kp',
        case ((gap - 1) % 7) + 1
          when 2 then 2 when 3 then 3 when 4 then 4 when 5 then 5 when 6 then 6 when 7 then 15 else 0 end,
        'streak:' || today, 'Day ' || gap || ' streak');
    end if;
  end if;

  select * into prof from public.arcade_profiles where id = uid;

  return jsonb_build_object(
    'ok', true,
    'session', session_uuid,
    'score', v_score,
    'xp', v_xp,
    'kp', v_kp,
    'accuracy', v_accuracy,
    'xpTotal', xp_total,
    'kpTotal', kp_total,
    'streakKp', streak_kp,
    'level', prof.level,
    'levelTotalXp', prof.total_xp,
    'kPoints', prof.k_points,
    'currentStreak', prof.current_streak,
    'longestStreak', prof.longest_streak,
    'achievements', unlocked,
    'challenges', challenges
  );
end;
$$;

-- ---------------------------------------------------------------- purchase

create or replace function public.arcade_purchase(p_item text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  price integer;
  balance integer;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  price := case p_item
    when 'theme-basic' then 50
    when 'theme-premium' then 100
    when 'avatar-accessory' then 75
    when 'badge-special' then 100
    when 'profile-decoration' then 150
    when 'challenge-pack' then 200
    else null end;

  if price is null then
    return jsonb_build_object('ok', false, 'reason', 'unknown item');
  end if;

  if exists (select 1 from public.arcade_purchases where user_id = uid and item_slug = p_item) then
    return jsonb_build_object('ok', false, 'reason', 'already owned');
  end if;

  -- single statement, guarded by the CHECK on k_points >= 0
  update public.arcade_profiles
    set k_points = k_points - price
    where id = uid and k_points >= price
    returning k_points into balance;

  if balance is null then
    return jsonb_build_object('ok', false, 'reason', 'not enough K-Points');
  end if;

  insert into public.arcade_purchases (user_id, item_slug, price) values (uid, p_item, price);
  perform public.arcade_grant(uid, 'purchase', p_item, 'kp-spend', price, 'purchase:' || p_item, p_item);

  return jsonb_build_object('ok', true, 'balance', balance, 'item', p_item);
end;
$$;

-- ---------------------------------------------------------------- leaderboard

create or replace function public.arcade_leaderboard(
  p_kind text default 'xp-all',
  p_game text default null,
  p_limit integer default 25,
  p_offset integer default 0
)
returns table (rank bigint, nickname text, value bigint, level integer, accuracy numeric)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if p_kind = 'game' and p_game is not null then
    return query
      select row_number() over (order by s.score desc, s.accuracy desc nulls last, s.created_at asc) as rank,
             pr.username,
             s.score::bigint,
             pr.level,
             s.accuracy
      from public.arcade_sessions s
      join public.arcade_profiles pr on pr.id = s.user_id
      where s.game_slug = p_game and s.verified
      order by s.score desc, s.accuracy desc nulls last, s.created_at asc
      limit least(greatest(p_limit, 1), 100) offset greatest(p_offset, 0);

  elsif p_kind = 'xp-week' then
    return query
      select row_number() over (order by sum(t.amount) desc) as rank,
             pr.username,
             sum(t.amount)::bigint,
             pr.level,
             null::numeric
      from public.arcade_reward_transactions t
      join public.arcade_profiles pr on pr.id = t.user_id
      where t.reward_type = 'xp'
        and t.created_at >= date_trunc('week', now() at time zone 'Asia/Kolkata')
      group by pr.username, pr.level, t.user_id
      order by sum(t.amount) desc
      limit least(greatest(p_limit, 1), 100) offset greatest(p_offset, 0);

  elsif p_kind = 'xp-month' then
    return query
      select row_number() over (order by sum(t.amount) desc) as rank,
             pr.username,
             sum(t.amount)::bigint,
             pr.level,
             null::numeric
      from public.arcade_reward_transactions t
      join public.arcade_profiles pr on pr.id = t.user_id
      where t.reward_type = 'xp'
        and t.created_at >= date_trunc('month', now() at time zone 'Asia/Kolkata')
      group by pr.username, pr.level, t.user_id
      order by sum(t.amount) desc
      limit least(greatest(p_limit, 1), 100) offset greatest(p_offset, 0);
  else
    return query
      select row_number() over (order by pr.total_xp desc) as rank,
             pr.username,
             pr.total_xp,
             pr.level,
             null::numeric
      from public.arcade_profiles pr
      order by pr.total_xp desc
      limit least(greatest(p_limit, 1), 100) offset greatest(p_offset, 0);
  end if;
end;
$$;

