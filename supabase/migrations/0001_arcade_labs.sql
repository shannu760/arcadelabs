-- Recalculates a session from raw facts. Mirrors public/assets/js/arcade/rules.js.
create or replace function public.arcade_calc(p_slug text, p jsonb)
returns jsonb
language plpgsql
immutable
as $$
declare
  score integer := 0;
  xp integer := 0;
  kp integer := 0;
  accuracy numeric := null;
  item jsonb;
  total integer := 0;
  good integer := 0;
  perfect boolean := false;
  highest integer := 0;
  hints integer := 0;
  dur numeric := 0;
  correct_chars integer := 0;
  wrong_chars integer := 0;
  mult numeric := 1;
  penalty numeric := 1;
  solved boolean := false;
  solved_at integer := 0;
  attempts integer := 0;
begin
  p := coalesce(p, '{}'::jsonb);

  if p_slug = 'brain-battle' then
    select count(*) into total from jsonb_array_elements(coalesce(p->'answers', '[]'::jsonb));
    if total < 5 then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    for item in select * from jsonb_array_elements(p->'answers') loop
      if (item->>'correct')::boolean then
        good := good + 1;
        score := score + 100 + case
          when coalesce((item->>'limitMs')::numeric, 0) = 0 then 5
          when coalesce((item->>'elapsedMs')::numeric, 0) / (item->>'limitMs')::numeric <= 0.25 then 20
          when coalesce((item->>'elapsedMs')::numeric, 0) / (item->>'limitMs')::numeric <= 0.50 then 15
          when coalesce((item->>'elapsedMs')::numeric, 0) / (item->>'limitMs')::numeric <= 0.75 then 10
          else 5
        end;
      end if;
    end loop;
    accuracy := good::numeric / total;
    xp := 10 + 5 * good + case when good = total then 20 else 0 end;
    kp := least(10, floor(accuracy * 10));
    perfect := good = total;

  elsif p_slug = 'memory-champion' then
    declare
      rounds_count integer := 0;
      positions integer := 0;
      perfect_rounds integer := 0;
    begin
      for item in select * from jsonb_array_elements(coalesce(p->'rounds', '[]'::jsonb)) loop
        rounds_count := rounds_count + 1;
        positions := positions + coalesce((item->>'total')::integer, 0);
        good := good + least(coalesce((item->>'correct')::integer, 0), coalesce((item->>'total')::integer, 0));
        score := score + 10 * least(coalesce((item->>'correct')::integer, 0), coalesce((item->>'total')::integer, 0));
        if coalesce((item->>'total')::integer, 0) > 0
           and coalesce((item->>'correct')::integer, 0) >= (item->>'total')::integer then
          perfect_rounds := perfect_rounds + 1;
          score := score + 25;
        end if;
      end loop;

      if rounds_count = 0 then
        return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
      end if;
      if perfect_rounds = rounds_count then
        score := score + 50;
        perfect := true;
      end if;
      accuracy := case when positions > 0 then least(1.0, good::numeric / positions) else null end;
      xp := 10 + 5 * rounds_count + case when perfect then 20 else 0 end;
      kp := least(10, floor(coalesce(accuracy, 0) * 10));
    end;

  elsif p_slug = '2048-challenge' then
    score := coalesce((p->>'score')::integer, 0);
    highest := coalesce((p->>'highestTile')::integer, 0);
    if coalesce((p->>'moves')::integer, 0) < 10 then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    xp := 5
      + case when highest >= 512 then 5 else 0 end
      + case when highest >= 1024 then 10 else 0 end
      + case when highest >= 2048 then 25 else 0 end;
    kp := case when highest >= 512 then 1 else 0 end
      + case when highest >= 1024 then 2 else 0 end
      + case when highest >= 2048 then 5 else 0 end;

  elsif p_slug = 'word-master' then
    select count(*) into attempts from jsonb_array_elements(coalesce(p->'attempts', '[]'::jsonb));
    if attempts = 0 or coalesce(p->>'target', '') = '' then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    -- letter scoring is reproduced here; the word list itself stays client-side
    select coalesce(sum(public.arcade_word_points(p->>'target', value)), 0)
      into score
      from jsonb_array_elements_text(p->'attempts');
    select coalesce(min(ord), 0) into solved_at from (
      select ord from jsonb_array_elements_text(p->'attempts') with ordinality as t(value, ord)
      where lower(value) = lower(p->>'target')
    ) s;
    if solved_at > 0 then
      solved := true;
      score := score + case solved_at
        when 1 then 100 when 2 then 80 when 3 then 60 when 4 then 40 when 5 then 20 else 10 end;
      xp := 5 + 15 + case when solved_at <= 3 then 10 else 0 end;
      kp := case when solved_at <= 2 then 8 when solved_at <= 4 then 6 else 4 end;
    else
      xp := 5;
      kp := 0;
    end if;

  elsif p_slug = 'typing-ninja' then
    dur := coalesce((p->>'durationSec')::numeric, 0);
    correct_chars := coalesce((p->>'correctChars')::integer, 0);
    wrong_chars := coalesce((p->>'incorrectChars')::integer, 0);
    if dur < 5 or correct_chars + wrong_chars < 10 then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    accuracy := correct_chars::numeric / (correct_chars + wrong_chars);
    score := round(correct_chars / 5.0 / (dur / 60.0));
    xp := 5 + case when accuracy >= 0.9 then 5 else 0 end + case when accuracy >= 0.98 then 10 else 0 end;
    kp := case when accuracy >= 0.98 then 5 when accuracy >= 0.9 then 2 else 0 end;

  elsif p_slug in ('code-escape', 'physics-lab') then
    declare
      arr jsonb := case when p_slug = 'code-escape' then coalesce(p->'challenges', '[]'::jsonb) else coalesce(p->'experiments', '[]'::jsonb) end;
      all_good boolean := true;
    begin
      select count(*) into total from jsonb_array_elements(arr);
      if total = 0 then
        return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
      end if;
      for item in select * from jsonb_array_elements(arr) loop
        if (item->>'correct')::boolean then
          good := good + 1;
          score := score + case lower(coalesce(item->>'difficulty', 'basic'))
            when 'intermediate' then 20 when 'advanced' then 30 else 10 end
            + case when p_slug = 'physics-lab' and coalesce((item->>'hintsUsed')::integer, 0) = 0 then 10 else 0 end;
          xp := xp + case lower(coalesce(item->>'difficulty', 'basic'))
            when 'intermediate' then 10 when 'advanced' then 15 else 5 end;
          kp := kp + case lower(coalesce(item->>'difficulty', 'basic'))
            when 'intermediate' then 2 when 'advanced' then 3 else 1 end;
        else
          all_good := false;
        end if;
      end loop;
      if all_good then xp := xp + 20; end if;
      kp := least(10, kp);
      accuracy := good::numeric / total;
    end;

  elsif p_slug = 'sudoku-master' then
    if not coalesce((p->>'solved')::boolean, false) then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    mult := case lower(coalesce(p->>'difficulty', 'easy'))
      when 'medium' then 1.5 when 'hard' then 2 else 1 end;
    hints := least(coalesce((p->>'hints')::integer, 0), 5);
    penalty := 1 - least(0.5, 0.1 * hints);
    score := round(100 * mult * penalty);
    accuracy := 1;
    xp := case lower(coalesce(p->>'difficulty', 'easy'))
      when 'medium' then 10 when 'hard' then 15 else 5 end;
    kp := case lower(coalesce(p->>'difficulty', 'easy'))
      when 'medium' then 2 when 'hard' then 3 else 1 end;

  elsif p_slug = 'geo-genius' then
    select count(*) into total from jsonb_array_elements(coalesce(p->'answers', '[]'::jsonb));
    if total < 5 then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    for item in select * from jsonb_array_elements(p->'answers') loop
      if (item->>'correct')::boolean then good := good + 1; end if;
    end loop;
    accuracy := good::numeric / total;
    perfect := good = total;
    score := good * 10 + case when perfect then 25 else 0 end;
    xp := 5 + case when perfect then 10 else 0 end;
    kp := 2 + case when perfect then 2 else 0 end;

  elsif p_slug = 'startup-tycoon' then
    if not coalesce((p->>'completed')::boolean, false) then
      return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
    end if;
    score := round(
      least(40, greatest(0, coalesce((p->>'profitability')::numeric, 0)))
      + least(25, greatest(0, coalesce((p->>'satisfaction')::numeric, 0)))
      + least(20, greatest(0, coalesce((p->>'resources')::numeric, 0)))
      + least(15, greatest(0, coalesce((p->>'decisions')::numeric, 0)))
    );
    xp := 10 + case when score >= 70 then 5 else 0 end + case when score >= 90 then 10 else 0 end;
    kp := case when score >= 70 then 2 else 0 end + case when score >= 90 then 3 else 0 end;

  else
    return jsonb_build_object('score', 0, 'xp', 0, 'kp', 0, 'accuracy', null, 'meta', '{}'::jsonb);
  end if;

  return jsonb_build_object(
    'score', greatest(0, score),
    'xp', greatest(0, xp),
    'kp', greatest(0, kp),
    'accuracy', accuracy,
    'meta', jsonb_build_object('perfect', coalesce(perfect, false))
  );
end;
$$;

-- Word scoring with the duplicate-letter two-pass rule.
create or replace function public.arcade_word_points(p_target text, p_guess text)
returns integer
language plpgsql
immutable
as $$
declare
  t text := lower(coalesce(p_target, ''));
  g text := lower(coalesce(p_guess, ''));
  pool text[] := '{}';
  marks text[] := '{}';
  i integer;
  at integer;
  pts integer := 0;
begin
  for i in 1 .. length(t) loop
    pool := array_append(pool, substr(t, i, 1));
  end loop;
  for i in 1 .. length(g) loop
    marks := array_append(marks, 'absent');
  end loop;
  for i in 1 .. length(g) loop
    if substr(g, i, 1) = pool[i] then
      marks[i] := 'correct';
      pool[i] := null;
    end if;
  end loop;
  for i in 1 .. length(g) loop
    if marks[i] = 'correct' then
      continue;
    end if;
    at := array_position(pool, substr(g, i, 1));
    if at is not null then
      marks[i] := 'present';
      pool[at] := null;
    end if;
  end loop;
  for i in 1 .. array_length(marks, 1) loop
    pts := pts + case marks[i] when 'correct' then 10 when 'present' then 5 else 0 end;
  end loop;
  return pts;
end;
$$;

