/* Generates supabase/migrations/0002_code_escape.sql from the challenge bank.

   The bank in public/assets/js/arcade/data/code-challenges.js is the authored
   copy the game ships with. This script mirrors it into Postgres so a
   configured database serves the exact same questions.

   Run:  node scripts/build-code-seed.mjs
*/

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { CHALLENGES, LEVELS } from '../public/assets/js/arcade/data/code-challenges.js';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'supabase', 'migrations', '0002_code_escape.sql');

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const jsonb = (value) => `${q(JSON.stringify(value))}::jsonb`;

const rows = CHALLENGES.map(
  (item) =>
    `  (${q(item.id)}, ${item.level}, ${q(item.difficulty)}, ${q(item.language)}, ${q(item.kind)}, ` +
    `${q(item.title)}, ${q(item.prompt)}, ${q(item.code)}, ${jsonb(item.options)}, ${item.answer}, ` +
    `${q(item.explain)}, ${q(item.source)})`,
).join(',\n');

const header = `-- ARCADE LABS — Code Escape question bank and per-player solves
--
-- Generated by scripts/build-code-seed.mjs from
-- public/assets/js/arcade/data/code-challenges.js. Edit that file and re-run
-- the script instead of hand-editing the seed below.
--
-- Apply after 0001:  Supabase dashboard → SQL Editor → paste → Run
--                    or: supabase db push
--
-- The ladder rule matches the client (data/code-challenges.js):
--   level 1 is always open, and ${LEVELS[1].unlockAt} correct answers in level N open level N+1.
-- The client never decides its own unlocks when cloud mode is on: it calls
-- arcade_code_solve() and reads back the level the database allows.
`;

const body = `-- ---------------------------------------------------------------- bank

create table if not exists public.arcade_code_challenges (
  slug       text primary key,
  level      integer not null check (level between 1 and 5),
  difficulty text not null check (difficulty in ('basic', 'intermediate', 'advanced')),
  language   text not null check (language in ('python', 'c', 'java')),
  kind       text not null check (kind in ('predict', 'debug', 'complete')),
  title      text not null,
  prompt     text not null,
  code       text not null,
  options    jsonb not null check (jsonb_array_length(options) between 2 and 6),
  answer     integer not null check (answer >= 0),
  explain    text not null,
  source     text not null default 'original' check (source in ('hackerrank', 'original')),
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  check (answer < jsonb_array_length(options))
);

create index if not exists arcade_code_challenges_level_idx
  on public.arcade_code_challenges (level, language);

-- ---------------------------------------------------------------- solves

create table if not exists public.arcade_code_solves (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid not null references auth.users (id) on delete cascade,
  challenge_slug text not null references public.arcade_code_challenges (slug) on delete cascade,
  level          integer not null,
  solved_at      timestamptz not null default now(),
  unique (user_id, challenge_slug)
);

create index if not exists arcade_code_solves_user_idx
  on public.arcade_code_solves (user_id, level);

-- ---------------------------------------------------------------- unlocks

-- Highest level the player may open. Mirrors unlockedLevel() in the client.
create or replace function public.arcade_code_unlocked(p_user uuid)
returns integer
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  lvl integer := 1;
  solved integer;
  requirement constant integer := ${LEVELS[1].unlockAt};
begin
  while lvl < 5 loop
    select count(*) into solved
      from public.arcade_code_solves s
      join public.arcade_code_challenges c on c.slug = s.challenge_slug
     where s.user_id = p_user
       and c.level = lvl
       and c.is_active;
    exit when solved < requirement;
    lvl := lvl + 1;
  end loop;
  return lvl;
end;
$$;

-- Record a run's correct answers. Unknown or inactive slugs are ignored, so a
-- client cannot unlock levels by inventing challenge ids.
create or replace function public.arcade_code_solve(p_slugs text[])
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  v_slug text;
  added integer := 0;
  lvl integer;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  for v_slug in select distinct unnest(coalesce(p_slugs, '{}'::text[])) loop
    insert into public.arcade_code_solves (user_id, challenge_slug, level)
    select uid, c.slug, c.level
      from public.arcade_code_challenges c
     where c.slug = v_slug and c.is_active
    on conflict (user_id, challenge_slug) do nothing;
    if found then
      added := added + 1;
    end if;
  end loop;

  lvl := public.arcade_code_unlocked(uid);
  return jsonb_build_object('ok', true, 'added', added, 'unlocked', lvl);
end;
$$;

create or replace function public.arcade_code_progress()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'solved', coalesce(
      (select jsonb_agg(challenge_slug order by challenge_slug)
         from public.arcade_code_solves where user_id = auth.uid()),
      '[]'::jsonb
    ),
    'unlocked', public.arcade_code_unlocked(auth.uid())
  );
$$;

-- ---------------------------------------------------------------- seed

insert into public.arcade_code_challenges
  (slug, level, difficulty, language, kind, title, prompt, code, options, answer, explain, source)
values
${rows}
on conflict (slug) do update set
  level      = excluded.level,
  difficulty = excluded.difficulty,
  language   = excluded.language,
  kind       = excluded.kind,
  title      = excluded.title,
  prompt     = excluded.prompt,
  code       = excluded.code,
  options    = excluded.options,
  answer     = excluded.answer,
  explain    = excluded.explain,
  source     = excluded.source,
  is_active  = true;

-- ---------------------------------------------------------------- RLS

alter table public.arcade_code_challenges enable row level security;
alter table public.arcade_code_solves enable row level security;

drop policy if exists arcade_code_challenges_read on public.arcade_code_challenges;
create policy arcade_code_challenges_read on public.arcade_code_challenges
  for select using (is_active);

drop policy if exists arcade_code_solves_read on public.arcade_code_solves;
create policy arcade_code_solves_read on public.arcade_code_solves
  for select using (auth.uid() = user_id);

revoke all on public.arcade_code_solves from anon, authenticated;
grant select on public.arcade_code_solves to authenticated;
grant select on public.arcade_code_challenges to anon, authenticated;

grant execute on function public.arcade_code_solve(text[]) to authenticated;
grant execute on function public.arcade_code_progress() to authenticated;
`;

await writeFile(outFile, `${header}\n${body}`, 'utf8');
console.log(`wrote ${outFile} — ${CHALLENGES.length} challenges`);
